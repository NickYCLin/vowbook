import { expect, test } from "@playwright/test";
import { encode } from "next-auth/jwt";

test.skip(process.env.VOWBOOK_CRUD_E2E !== "1", "需要隔離 CRUD 合成資料。");

test("頭貼可上傳、更換與移除，並顯示於使用者及回饋管理", async ({ page, context, request }, info) => {
  const email = process.env.VOWBOOK_CRUD_E2E_EMAIL;
  const subject = process.env.VOWBOOK_CRUD_E2E_GOOGLE_SUBJECT;
  if (!email || !subject) throw new Error("Missing isolated CRUD identity");
  const token = await encode({ secret: process.env.AUTH_SECRET ?? "vowbook-e2e-local-secret-not-for-production", maxAge: 3600, token: { googleSubject: subject, email, name: "合成擁有者" } });
  await context.addCookies([{ name: "vowbook.session-token", value: token, domain: "127.0.0.1", path: "/VowBook", httpOnly: true, secure: false, sameSite: "Lax" }]);
  await page.goto("./dashboard");
  await page.getByLabel(/^開啟帳號與外觀選單/).click();
  const sharp = (await import("sharp")).default;
  const image = await sharp({ create: { width: 32, height: 32, channels: 3, background: "#996644" } }).png().toBuffer();
  const input = page.getByLabel("選擇自訂頭像");
  await input.setInputFiles({ name: "synthetic-avatar.png", mimeType: "image/png", buffer: image });
  await expect(page.getByText("已更新自訂頭像。", { exact: true })).toBeVisible();
  const initialSource = await page.getByTestId("account-avatar-image").getAttribute("src");
  const replacement = await sharp({ create: { width: 32, height: 32, channels: 3, background: "#446699" } }).webp().toBuffer();
  await input.setInputFiles({ name: "replacement.webp", mimeType: "image/webp", buffer: replacement });
  await expect(page.getByTestId("account-avatar-image")).not.toHaveAttribute("src", initialSource!);
  await page.goto("./admin/users");
  const card = page.getByRole("article").filter({ hasText: email });
  const avatar = card.getByRole("img");
  await expect(avatar).toBeVisible();
  await expect(avatar).toHaveJSProperty("naturalWidth", 256);
  const source = await avatar.getAttribute("src");
  if (!source) throw new Error("Missing admin avatar source");
  expect((await request.get(source)).status()).toBe(401);
  const fixtureData = process.env.VOWBOOK_CRUD_E2E_FIXTURES;
  if (!fixtureData) throw new Error("Missing isolated CRUD fixtures");
  const fixtures = JSON.parse(fixtureData) as Record<string, { workspaceId: string; memberId: string; memberEmail: string }>;
  const fixture = fixtures[info.project.name.startsWith("mobile") ? "mobile" : "desktop"];
  const memberToken = await encode({ secret: process.env.AUTH_SECRET ?? "vowbook-e2e-local-secret-not-for-production", maxAge: 3600, token: { googleSubject: `${fixture.memberId}-subject`, email: fixture.memberEmail } });
  expect((await request.get(source, { headers: { Cookie: `vowbook.session-token=${memberToken}` } })).status()).toBe(404);
  await page.screenshot({ path: info.outputPath("admin-users-avatar.png") });
  await page.goto(`./workspaces/${fixture.workspaceId}/timeline`);
  if (info.project.name.startsWith("mobile")) await page.getByRole("button", { name: "更多", exact: true }).click();
  await page.getByRole("button", { name: "意見回饋", exact: true }).click();
  await page.getByRole("textbox", { name: "回饋內容" }).fill(`頭貼驗證-${info.project.name}`);
  await page.getByRole("button", { name: "送出回饋", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("你的回饋已保存");
  await page.goto("./admin/feedback");
  const feedback = page.getByRole("article").filter({ hasText: `頭貼驗證-${info.project.name}` });
  await expect(feedback.getByRole("img")).toHaveJSProperty("naturalWidth", 256);
  await page.screenshot({ path: info.outputPath("admin-feedback-avatar.png") });
  await page.getByLabel(/^開啟帳號與外觀選單/).click();
  await page.getByRole("button", { name: "移除自訂頭像", exact: true }).click();
  await expect(page.getByText("已移除自訂頭像，改用姓名縮寫。", { exact: true })).toBeVisible();
  await page.reload();
  await expect(feedback.getByRole("img")).toHaveCount(0);
  await expect(feedback.getByLabel("CRUD E2E 擁有者的頭貼")).toBeVisible();
});
