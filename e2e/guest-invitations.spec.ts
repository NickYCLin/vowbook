import { expect, test } from "@playwright/test";
import { encode } from "next-auth/jwt";
import sharp from "sharp";
import { writeFile } from "node:fs/promises";
test.skip(process.env.VOWBOOK_CRUD_E2E !== "1", "需要隔離 CRUD 合成資料。");
test("自訂題目、免登入回覆、本人座位圖與工作人員報到碼完整流程", async ({ page, context, browser }, info) => {
  const subject = process.env.VOWBOOK_CRUD_E2E_GOOGLE_SUBJECT, email = process.env.VOWBOOK_CRUD_E2E_EMAIL;
  const encoded = process.env.VOWBOOK_CRUD_E2E_FIXTURES, mobileToken = process.env.VOWBOOK_CRUD_E2E_MOBILE_TOKEN;
  if (!subject || !email || !encoded || !mobileToken) throw new Error("Missing isolated invitation fixtures");
  const fixtures = JSON.parse(encoded) as Record<string, { workspaceId: string; manualGuestId: string; editedGuestName: string; importedGuestName: string }>;
  const fixture = fixtures[info.project.name.startsWith("mobile") ? "mobile" : "desktop"];
  const base = process.env.NEXT_PUBLIC_BASE_PATH ?? "";
  const session = await encode({ secret: process.env.AUTH_SECRET ?? "vowbook-e2e-local-secret-not-for-production", maxAge: 3600, token: { googleSubject: subject, email, name: "合成擁有者" } });
  await context.addCookies([{ name: "vowbook.session-token", value: session, domain: "127.0.0.1", path: base || "/", httpOnly: true, secure: false, sameSite: "Lax" }]);
  const headers = { Authorization: `Bearer ${mobileToken}` };
  const mobileRoot = `http://127.0.0.1:3100${base}/api/mobile/v1/workspaces/${fixture.workspaceId}`;
  const originalPlan = await context.request.get(`${mobileRoot}/tables`, { headers });
  expect(originalPlan.status()).toBe(200);
  const unassigned = (await originalPlan.json()).unassignedGuests.find((item: { id: string }) => item.id === fixture.manualGuestId);
  expect(unassigned).toBeTruthy();
  const createdTable = await context.request.post(`${mobileRoot}/seating-tables`, { headers, data: { name: "合成邀請座位驗證桌", capacity: 20, notes: "" } });
  expect(createdTable.status()).toBe(201); const table = (await createdTable.json()).table;
  const assigned = await context.request.patch(`${mobileRoot}/tables/${fixture.manualGuestId}`, { headers,
    data: { tableId: table.id, expectedVersion: unassigned.version, expectedTableId: null } });
  expect(assigned.status()).toBe(200); const assignedVersion = (await assigned.json()).seating.version;
  const currentPlan = await context.request.get(`${mobileRoot}/tables`, { headers });
  const tableNumber = (await currentPlan.json()).tables.find((item: { id: string }) => item.id === table.id).number;
  await page.goto(`./workspaces/${fixture.workspaceId}/guests/invitations`);
  await page.getByLabel("會館名稱", { exact: true }).fill("合成測試會館");
  await page.getByRole("button", { name: "新增自訂題目", exact: true }).click();
  await page.getByLabel("自訂題目 1", { exact: true }).fill("是否需要接駁");
  await page.getByRole("combobox", { name: "第 1 題類型", exact: true }).selectOption("CHOICE");
  await page.getByLabel(/第 1 題選項/).fill("需要\n不需要");
  await page.getByLabel("第 1 題必填", { exact: true }).check();
  await page.getByRole("button", { name: "儲存邀請表單", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("邀請表單已儲存。");
  const venueImage = await sharp({ create: { width: 100, height: 80, channels: 3, background: "#f5eee4" } }).png().toBuffer();
  await page.getByLabel("上傳會館圖", { exact: true }).setInputFiles({ name: "synthetic-venue.png", mimeType: "image/png", buffer: venueImage });
  await expect(page.getByRole("status")).toHaveText("會館圖已更新，將提供給受邀賓客。");
  const row = page.getByRole("article", { name: `邀請回覆：${fixture.editedGuestName}`, exact: true });
  await row.getByRole("button", { name: "建立專屬連結", exact: true }).click();
  const link = await page.getByRole("textbox", { name: "賓客專屬邀請連結", exact: true }).inputValue();
  const invitationToken = new URL(link).hash.slice(1);
  expect(invitationToken.length).toBe(43);
  const visitor = await browser.newContext(info.project.use);
  const guest = await visitor.newPage(), urls: string[] = [];
  guest.on("request", (request) => urls.push(request.url()));
  try {
    await guest.goto(link);
    await expect(guest.getByRole("heading", { name: "回覆邀請", exact: true })).toBeVisible();
    await expect(guest.getByText(`親愛的${fixture.editedGuestName}，這是你這組賓客的專屬邀請。`, { exact: true })).toBeVisible();
    await expect(guest.getByText(fixture.importedGuestName, { exact: true })).toHaveCount(0);
    await expect(guest.getByText(`你的桌次：${tableNumber} 號桌 · 合成邀請座位驗證桌`, { exact: true })).toBeVisible();
    await expect(guest.locator("svg").getByText("你的桌次", { exact: true })).toBeVisible();
    await guest.getByLabel("出席人數（含本人）", { exact: true }).fill("2");
    await guest.getByLabel("其中素食人數", { exact: true }).fill("1");
    await guest.getByRole("combobox", { name: "是否需要接駁（必填）", exact: true }).selectOption("需要");
    await guest.getByRole("button", { name: "儲存回覆", exact: true }).click();
    await expect(guest.getByRole("status")).toHaveText("回覆已儲存，謝謝！若資料有變更，可再次修改後儲存。");
    await expect(guest.getByRole("img", { name: "主辦方提供的會館平面圖", exact: true })).toBeVisible();
    const qrImage = guest.getByRole("img", { name: "本組賓客專屬報到 QR Code", exact: true });
    await expect(qrImage).toBeVisible();
    const imageData = await qrImage.getAttribute("src");
    if (!imageData?.startsWith("data:image/png;base64,")) throw new Error("Missing generated QR image");
    await writeFile(info.outputPath("guest-check-in-qr.png"), Buffer.from(imageData.split(",")[1], "base64"));
    await guest.getByText("顯示供工作人員手動輸入的報到碼", { exact: true }).click();
    const code = await guest.getByRole("region", { name: "賓客報到碼" }).locator("details p").innerText();
    expect(code.startsWith("vowbook:check-in:v1:")).toBe(true);
    expect(code.includes(invitationToken)).toBe(false);
    const path = `${base}/api/mobile/v1/workspaces/${fixture.workspaceId}/check-in`;
    expect((await guest.request.post(`http://127.0.0.1:3100${path}/scan`, { data: { code } })).status()).toBe(401);
    const scanned = await context.request.post(`http://127.0.0.1:3100${path}/scan`, { headers, data: { code } });
    expect(scanned.status()).toBe(200);
    const preview = await scanned.json(); expect(preview.guest.id).toBe(fixture.manualGuestId); expect(preview.guest.checkIn).toBeNull();
    const checked = await context.request.post(`http://127.0.0.1:3100${path}/${fixture.manualGuestId}`, { headers, data: { headcount: 2 } });
    expect(checked.status()).toBe(201); const record = (await checked.json()).checkIn;
    const rescanned = await context.request.post(`http://127.0.0.1:3100${path}/scan`, { headers, data: { code } });
    expect((await rescanned.json()).guest.checkIn.headcount).toBe(2);
    await context.request.delete(`http://127.0.0.1:3100${path}/${fixture.manualGuestId}`, { headers, data: { checkInId: record.id, expectedVersion: record.version } });
    expect(urls.every((url) => !url.includes(invitationToken))).toBe(true);
    expect(await guest.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
    await guest.screenshot({ path: info.outputPath("guest-invitation.png"), fullPage: true });
    await page.reload();
    await expect(page.getByRole("main").getByLabel("邀請回覆統計", { exact: true })).toContainText("回覆出席 2 人（素食 1 人）");
    await row.getByText("查看回覆內容", { exact: true }).click();
    await expect(row.getByText("需要", { exact: true })).toBeVisible();
    await page.screenshot({ path: info.outputPath("invitation-management.png"), fullPage: true });
    page.once("dialog", (dialog) => dialog.accept());
    await row.getByRole("button", { name: "撤銷連結", exact: true }).click();
    await expect(page.getByRole("status")).toHaveText("連結與 QR 碼已撤銷，既有回覆仍保留。");
    const revoked = await guest.request.post(`http://127.0.0.1:3100${base}/api/guest-invitations/view`, { headers: { Authorization: `Bearer ${invitationToken}` } });
    expect(revoked.status()).toBe(404);
    const removed = await context.request.patch(`${mobileRoot}/tables/${fixture.manualGuestId}`, { headers,
      data: { tableId: null, expectedVersion: assignedVersion, expectedTableId: table.id } });
    expect(removed.status()).toBe(200);
    expect((await context.request.delete(`${mobileRoot}/seating-tables/${table.id}`, { headers, data: { expectedVersion: table.version } })).status()).toBe(200);
  } finally { await visitor.close(); }
});
